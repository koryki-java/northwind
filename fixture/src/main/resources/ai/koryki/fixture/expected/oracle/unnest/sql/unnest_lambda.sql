  t.nr
, s.COLUMN_VALUE
FROM
 check_complex t
  CROSS APPLY TABLE(CASE WHEN t.scores IS NULL THEN NULL ELSE CAST(MULTISET(SELECT LA0.X FROM (SELECT COLUMN_VALUE X, ROWNUM I FROM TABLE(t.scores) Z) LA0 WHERE LA0.X > 5 ORDER BY LA0.I) AS SYS.ODCINUMBERLIST) END) s